use crate::sync::{Condvar, Mutex, MutexBlocking, MutexSpin, Semaphore};
use crate::task::{block_current_and_run_next, current_process, current_task};
use crate::timer::{add_timer, get_time_ms};
use alloc::sync::Arc;
use alloc::vec::Vec;
/// sleep syscall
pub fn sys_sleep(ms: usize) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_sleep",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task()
            .unwrap()
            .inner_exclusive_access()
            .res
            .as_ref()
            .unwrap()
            .tid
    );
    let expire_ms = get_time_ms() + ms;
    let task = current_task().unwrap();
    add_timer(expire_ms, task);
    block_current_and_run_next();
    0
}
/// mutex create syscall
pub fn sys_mutex_create(blocking: bool) -> isize {
    trace!(
        "kernel:pid[{}] tid[{}] sys_mutex_create",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        current_task()
            .unwrap()
            .inner_exclusive_access()
            .res
            .as_ref()
            .unwrap()
            .tid
    );
    let process = current_process();
    let mutex: Option<Arc<dyn Mutex>> = if !blocking {
        Some(Arc::new(MutexSpin::new()))
    } else {
        Some(Arc::new(MutexBlocking::new()))
    };
    let mut process_inner = process.inner_exclusive_access();
    if let Some(id) = process_inner
        .mutex_list
        .iter()
        .enumerate()
        .find(|(_, item)| item.is_none())
        .map(|(id, _)| id)
    {
        process_inner.mutex_list[id] = mutex;
        id as isize
    } else {
        process_inner.mutex_list.push(mutex);
        process_inner.mutex_list.len() as isize - 1
    }
}
/// mutex lock syscall
pub fn sys_mutex_lock(mutex_id: usize) -> isize {
    let tid = current_task()
        .unwrap()
        .inner_exclusive_access()
        .res
        .as_ref()
        .unwrap()
        .tid;
    trace!(
        "kernel:pid[{}] tid[{}] sys_mutex_lock",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        tid
    );
    let process = current_process();
    let mut process_inner = process.inner_exclusive_access();
    let mutex = Arc::clone(process_inner.mutex_list[mutex_id].as_ref().unwrap());

    if process_inner.dead_detect {
        let available: Vec<bool> = process_inner
            .mutex_list
            .iter()
            .map(|mutex_opt| {
                if let Some(mutex) = mutex_opt {
                    mutex.available()
                } else {
                    false
                }
            })
            .collect();
        let mut finish: Vec<bool> = [true].repeat(process_inner.tasks.len());
        let need = &mut process_inner.mutex_needed;
        while tid + 1 > need.len() {
            need.push(None);
        }
        need[tid] = Some(mutex_id);
        need.iter().enumerate().for_each(|(i, n)| {
            if n.is_some() {
                finish[i] = false
            }
        });
        let mut work: Vec<bool> = available.clone();

        loop {
            let pos = finish.iter().enumerate().position(|(i, fi)| {
                if !fi {
                    let req = process_inner.mutex_needed[i].unwrap();
                    work[req]
                } else {
                    false
                }
            });

            match pos {
                // step 3
                Some(p) => {
                    let allocated = &mut process_inner.mutex_allocated;
                    while tid + 1 > allocated.len() {
                        allocated.push(None);
                    }
                    if let Some(allocated_vec) = &allocated[p] {
                        for id in allocated_vec {
                            work[*id] = true;
                        }
                    }
                    finish[p] = true;
                }
                // step 4
                None => {
                    if let Some(_) = finish.iter().find(|&&fi| !fi) {
                        // dead
                        process_inner.mutex_needed[tid] = None; // failed to lock
                        return -0xDEAD;
                    } else {
                        if available[mutex_id] {
                            let allocated = &mut process_inner.mutex_allocated;
                            while tid + 1 > allocated.len() {
                                allocated.push(None);
                            }
                            if let Some(allocated_vec) = &mut allocated[tid] {
                                allocated_vec.push(mutex_id);
                            } else {
                                allocated[tid] = Some(Vec::from([mutex_id]));
                            }
                        }
                    }
                    break;
                }
            }
        }
    }
    drop(process_inner);
    drop(process);
    mutex.lock();
    0
}
/// mutex unlock syscall
pub fn sys_mutex_unlock(mutex_id: usize) -> isize {
    let tid = current_task()
        .unwrap()
        .inner_exclusive_access()
        .res
        .as_ref()
        .unwrap()
        .tid;
    trace!(
        "kernel:pid[{}] tid[{}] sys_mutex_unlock",
        current_task().unwrap().process.upgrade().unwrap().getpid(),
        tid
    );
    let process = current_process();
    let mut process_inner = process.inner_exclusive_access();
    let mutex = Arc::clone(process_inner.mutex_list[mutex_id].as_ref().unwrap());
    if process_inner.dead_detect {
        if let Some(allocated) = process_inner.mutex_allocated[tid].as_mut() {
            allocated.retain(|&id| id != mutex_id);
        }
    }
    drop(process_inner);
    drop(process);
    mutex.unlock();
    0
}
